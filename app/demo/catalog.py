_UNITS = {"г": PackageUnit.GRAM, "мл": PackageUnit.MILLILITER, "шт": PackageUnit.PIECE}

ASSORTMENT_SHARE = 0.85
IN_STOCK_SHARE = 0.95


def build_demo_catalog(now: datetime, seed: int = 2026) -> ParsedCatalog:
    rng = random.Random(seed)  # noqa: S311 (это не криптография, а воспроизводимые демо-данные)
    catalog = ParsedCatalog(is_synthetic=True)

    for external_id, chain, name, address, lat, lon, store_format, _ in _STORES:
        catalog.stores.append(
            StoreRecord(external_id, chain, name, address, lat, lon, store_format, is_active=True)
        )

    base_prices: dict[str, int] = {}
    for category, product_type, title, unit, sizes in _PRODUCTS:
        for amount, base_rubles in sizes:
            external_id = f"demo-{len(catalog.products) + 1}"
            catalog.products.append(
                ProductRecord(
                    external_id=external_id,
                    name=f"Демо {title}, {amount} {unit}",
                    brand="Демо",
                    category=category,
                    product_type=product_type,
                    package_amount=Decimal(amount),
                    package_unit=_UNITS[unit],
                    attributes={"synthetic": True},
                )
            )
            base_prices[external_id] = base_rubles

    for store_id, *_, chain_factor in _STORES:
        for product in catalog.products:
            if rng.random() > ASSORTMENT_SHARE:
                continue
            rubles = base_prices[product.external_id] * chain_factor * rng.uniform(0.9, 1.1)
            catalog.offers.append(
                OfferRecord(
                    row=len(catalog.offers) + 2,
                    store_external_id=store_id,
                    product_external_id=product.external_id,
                    price_kopecks=max(1000, round(rubles) * 100 - 1),
                    card_price_kopecks=None,
                    in_stock=rng.random() < IN_STOCK_SHARE,
                    source_updated_at=now - timedelta(minutes=rng.randint(0, 6 * 60)),
                    price_type="regular",
                    price_conditions=None,
                    source_product_id=None,
                    source_url=None,
                )
            )
    return catalog
